/**
 * A debug configuration as it appears in launch.json.
 */
export interface IDebugConfiguration {
	type: string;
	name: string;
	request: string;
	[key: string]: unknown;
}

/**
 * Something in a cppdbg/cppvsdbg configuration that could not be carried over to CodeLLDB.
 */
export type TranslationIssue =
	/** A property that only makes sense for the Microsoft debuggers and is dropped. */
	| { readonly kind: 'ignoredProperty'; readonly property: string }
	/** A setup command that is not an LLDB command line command and is dropped. */
	| { readonly kind: 'ignoredSetupCommand'; readonly command: string }
	/** A property that changes what is debugged in a way CodeLLDB cannot reproduce. */
	| { readonly kind: 'unsupportedProperty'; readonly property: string };

export interface ITranslationResult {
	readonly configuration: IDebugConfiguration;
	readonly issues: readonly TranslationIssue[];
}

/**
 * Properties that only affect how the Microsoft debug adapters drive gdb, lldb-mi or vsdbg.
 */
const ignoredProperties = new Set([
	'avoidWindowsConsoleRedirection',
	'customLaunchSetupCommands',
	'debuginfod',
	'enableDebugHeap',
	'filterStderr',
	'filterStdout',
	'hardwareBreakpoints',
	'ignoreRunWithoutDebuggingWarnings',
	'launchCompleteCommand',
	'logging',
	'miDebuggerArgs',
	'miDebuggerPath',
	'postRemoteConnectCommands',
	'processFilter',
	'requireExactSource',
	'serverLaunchTimeout',
	'serverStarted',
	'showDisplayString',
	'stopAtConnect',
	'svdPath',
	'symbolLoadInfo',
	'symbolOptions',
	'targetArchitecture',
	'unknownBreakpointHandling',
	'useExtendedRemote',
	'variables',
	'visualizerFile',
]);

/**
 * Properties that make the Microsoft debug adapters debug somewhere else (over a pipe, through a debug
 * server they start, after deploying). Silently dropping them would debug the wrong thing.
 */
const unsupportedProperties = new Set([
	'debugServerArgs',
	'debugServerPath',
	'deploySteps',
	'pipeTransport',
]);

/**
 * Translates a cppdbg or cppvsdbg launch configuration (Microsoft C/C++ extension) into an equivalent
 * CodeLLDB (`lldb`) configuration. Properties that are not specific to cppdbg/cppvsdbg (`preLaunchTask`,
 * `presentation`, CodeLLDB properties, ...) are passed through unchanged.
 */
/**
 * Writes LLDB commands to a file and returns its path.
 */
export type LldbCommandFileWriter = (commands: readonly string[]) => string;

/**
 * A part of a generated LLDB command: text, an argument to quote, a list of directories separated by `;` to quote
 * as separate arguments, or a command to run from a command file.
 */
type LldbCommandPart = string | { readonly kind: 'argument' | 'argumentList' | 'commandFile'; readonly value: string };

/**
 * A generated LLDB command that is completed after VS Code has substituted the variables in it.
 */
interface IPendingLldbCommand {
	/** The command used until then, for example by CodeLLDB's process picker while substituting variables. */
	readonly provisional: string;
	readonly parts: readonly LldbCommandPart[];
}

/**
 * Generated LLDB commands contain values from the configuration, which can contain variables. Arguments can only be
 * quoted after VS Code has substituted the variables, so the parts of the commands are kept in this property, where
 * VS Code substitutes variables too, until {@link completeLldbCommands} completes the commands.
 */
const pendingLldbCommandsProperty = 'cpptoolsCompatPendingLldbCommands';

const lldbCommandProperties = ['initCommands', 'targetCreateCommands', 'processCreateCommands', 'preRunCommands'];

/**
 * Completes the LLDB commands generated by {@link translateCppDebugConfiguration}, after VS Code has substituted
 * the variables in the configuration: arguments are quoted, and command files are written.
 */
export function completeLldbCommands(configuration: IDebugConfiguration, writeCommandFile: LldbCommandFileWriter): IDebugConfiguration {
	const pending = configuration[pendingLldbCommandsProperty];
	delete configuration[pendingLldbCommandsProperty];
	if (!Array.isArray(pending)) {
		return configuration;
	}
	const remaining = [...pending as IPendingLldbCommand[]];
	for (const property of lldbCommandProperties) {
		const commands = configuration[property];
		if (!Array.isArray(commands)) {
			continue;
		}
		configuration[property] = commands.map(command => {
			const index = remaining.findIndex(pendingCommand => pendingCommand.provisional === command);
			if (index < 0) {
				return command;
			}
			const [{ parts }] = remaining.splice(index, 1);
			let emptyList = false;
			const completed = parts.map(part => {
				if (typeof part === 'string') {
					return part;
				}
				switch (part.kind) {
					case 'argument':
						return quoteLldbArgument(part.value);
					case 'argumentList': {
						const values = splitSearchPath(part.value);
						emptyList ||= values.length === 0;
						return values.map(quoteLldbArgument).join(' ');
					}
					case 'commandFile':
						return quoteLldbArgument(writeCommandFile([part.value]));
				}
			}).join('');
			// A list that is empty after substituting variables has nothing to add
			return emptyList ? `# ${completed}` : completed;
		});
	}
	return configuration;
}

export function translateCppDebugConfiguration(source: IDebugConfiguration, platform: NodeJS.Platform): ITranslationResult {
	const issues: TranslationIssue[] = [];
	// The debug service applies the platform specific properties of launch.json configurations before resolving
	// them, but not of configurations passed to `vscode.debug.startDebugging`. Applying them again is harmless.
	const platformProperties = source[platform === 'win32' ? 'windows' : platform === 'darwin' ? 'osx' : 'linux'];
	const effective: IDebugConfiguration = platformProperties && typeof platformProperties === 'object' ? { ...source, ...platformProperties } : source;
	const configuration: IDebugConfiguration = { ...effective, type: 'lldb' };
	const miMode = typeof effective.MIMode === 'string' ? effective.MIMode : (platform === 'darwin' ? 'lldb' : 'gdb');
	const initCommands: string[] = [];
	const pendingCommands: IPendingLldbCommand[] = [];

	const lldbCommand = (parts: LldbCommandPart[], provisional?: string): string => {
		provisional ??= parts.map(part =>
			typeof part === 'string' ? part
				: part.kind === 'argumentList' ? splitSearchPath(part.value).map(quoteLldbArgument).join(' ')
					: quoteLldbArgument(part.value)
		).join('');
		pendingCommands.push({ provisional, parts });
		return provisional;
	};

	const take = <T>(property: string): T | undefined => {
		const value = configuration[property];
		delete configuration[property];
		return value as T | undefined;
	};

	delete configuration.MIMode;

	const environment = take<unknown>('environment');
	if (Array.isArray(environment)) {
		const env: Record<string, string> = {};
		for (const entry of environment) {
			if (entry && typeof entry.name === 'string') {
				env[entry.name] = entry.value === undefined || entry.value === null ? '' : String(entry.value);
			}
		}
		configuration.env = { ...env, ...(configuration.env as Record<string, string> | undefined) };
	} else if (environment && typeof environment === 'object') {
		configuration.env = { ...(environment as Record<string, string>), ...(configuration.env as Record<string, string> | undefined) };
	}

	// The Microsoft debuggers stop at the program's entry point, `main`, or on Windows also `wmain`, `WinMain` or
	// `wWinMain`. CodeLLDB's stopOnEntry stops at the first instruction of the process
	const stopAtEntry = take<boolean>('stopAtEntry');
	// CodeLLDB runs preRunCommands also when running without debugging
	if (stopAtEntry && configuration.request === 'launch' && !configuration.noDebug) {
		const entryPoints = platform === 'win32' ? ['main', 'wmain', 'WinMain', 'wWinMain'] : ['main'];
		const breakpoint = `breakpoint set --one-shot true ${entryPoints.map(name => `--name ${name}`).join(' ')}`;
		configuration.preRunCommands = [breakpoint, ...(configuration.preRunCommands as string[] | undefined ?? [])];
	}

	// cppvsdbg's `console` uses different values than CodeLLDB's `console` alias, so it is always translated
	const consoleKind = take<string>('console');
	const externalConsole = take<boolean>('externalConsole');
	if (configuration.terminal === undefined) {
		const terminal = translateConsole(consoleKind) ?? (externalConsole ? 'external' : undefined);
		if (terminal) {
			configuration.terminal = terminal;
		}
	}

	const processId = take<string | number>('processId');
	if (processId !== undefined && configuration.pid === undefined) {
		configuration.pid = processId;
	}

	const sourceFileMap = take<Record<string, unknown>>('sourceFileMap');
	if (sourceFileMap && typeof sourceFileMap === 'object') {
		const sourceMap: Record<string, string> = {};
		for (const [remote, local] of Object.entries(sourceFileMap)) {
			if (typeof local === 'string') {
				sourceMap[remote] = local;
			} else if (local && typeof local === 'object' && typeof (local as { editorPath?: unknown }).editorPath === 'string') {
				sourceMap[remote] = (local as { editorPath: string }).editorPath;
			}
		}
		configuration.sourceMap = { ...sourceMap, ...(configuration.sourceMap as Record<string, string> | undefined) };
	}

	// The lists are split after substituting variables, which can contain several directories
	for (const [property, setting] of [['additionalSOLibSearchPath', 'target.exec-search-paths'], ['symbolSearchPath', 'target.debug-file-search-paths']]) {
		const searchPath = take<unknown>(property);
		if (typeof searchPath === 'string' && splitSearchPath(searchPath).length > 0) {
			initCommands.push(lldbCommand([`settings append ${setting} `, { kind: 'argumentList', value: searchPath }]));
		}
	}

	const setupCommands = take<unknown>('setupCommands');
	if (Array.isArray(setupCommands)) {
		for (const setupCommand of setupCommands) {
			const text = typeof setupCommand?.text === 'string' ? setupCommand.text.trim() : '';
			if (!text) {
				continue;
			}
			// Commands starting with '-' are GDB/MI commands, and without MIMode lldb the rest are gdb commands
			if (text.startsWith('-') || miMode !== 'lldb') {
				issues.push({ kind: 'ignoredSetupCommand', command: text });
			} else if (setupCommand.ignoreFailures === true) {
				// CodeLLDB stops the launch when a command fails, but `command source` can continue after failures.
				// (CodeLLDB's `nofail` command needs Python, which the Malterlib liblldb doesn't have.)
				// Until it is completed the command is a comment, so that it can't fail CodeLLDB's process picker
				initCommands.push(lldbCommand(['command source --stop-on-error false ', { kind: 'commandFile', value: text }], `# ${text}`));
			} else {
				initCommands.push(text);
			}
		}
	}

	if (initCommands.length) {
		configuration.initCommands = [...initCommands, ...(configuration.initCommands as string[] | undefined ?? [])];
	}

	const coreDumpPath = take<string>('coreDumpPath');
	const dumpPath = take<string>('dumpPath');
	const dumpFile = coreDumpPath || dumpPath;
	const debugServerAddress = take<string>('miDebuggerServerAddress');
	if (dumpFile) {
		const program: LldbCommandPart[] = typeof configuration.program === 'string' ? [{ kind: 'argument', value: configuration.program }, ' '] : [];
		configuration.request = 'launch';
		configuration.targetCreateCommands = [lldbCommand(['target create ', ...program, '--core ', { kind: 'argument', value: dumpFile }])];
		configuration.processCreateCommands = [];
		delete configuration.pid;
	} else if (debugServerAddress) {
		// CodeLLDB creates the target from `program` and connects instead of launching or attaching. The
		// request is kept, so that stopping debugging detaches from an attached process instead of killing it.
		// The process is stopped once connected, which CodeLLDB reports rather than resuming it, while the
		// Microsoft debuggers run it to a breakpoint, or to the entry point with stopAtEntry.
		configuration.processCreateCommands = [`gdb-remote ${debugServerAddress}`, 'process continue'];
		if (configuration.request !== 'attach') {
			delete configuration.pid;
		}
	}

	for (const property of Object.keys(configuration)) {
		if (unsupportedProperties.has(property)) {
			issues.push({ kind: 'unsupportedProperty', property });
			delete configuration[property];
		} else if (ignoredProperties.has(property)) {
			issues.push({ kind: 'ignoredProperty', property });
			delete configuration[property];
		}
	}

	// The platform specific properties are applied. Resolving variables applies them again, which would bring
	// back the untranslated properties.
	delete configuration.windows;
	delete configuration.linux;
	delete configuration.osx;

	if (pendingCommands.length) {
		configuration[pendingLldbCommandsProperty] = pendingCommands;
	}

	return { configuration, issues };
}

function translateConsole(consoleKind: string | undefined): string | undefined {
	switch (consoleKind) {
		case 'internalConsole': return 'console';
		case 'integratedTerminal': return 'integrated';
		case 'externalTerminal':
		case 'newExternalWindow': return 'external';
		default: return undefined;
	}
}

function splitSearchPath(searchPath: string): string[] {
	return searchPath.split(';').map(directory => directory.trim()).filter(directory => directory.length > 0);
}

function quoteLldbArgument(value: string): string {
	return `"${value.replace(/[\\"]/g, match => `\\${match}`)}"`;
}
